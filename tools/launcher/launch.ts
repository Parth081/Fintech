/** Stage processes (services/stages). Since M2 the ledger is its own service (services/ledger), not a stage. */
export const STAGES = ['screening', 'risk', 'fx', 'routing', 'settlement', 'reconciliation'] as const;
export type Stage = (typeof STAGES)[number];

/** Every process the launcher manages, in start order. Names accepted by restart()/kill(). */
export const SERVICE_NAMES = ['broker', 'payment-api', ...STAGES, 'ledger', 'orchestrator', 'ops', 'assistant', 'booth', 'gateway'] as const;
export type ServiceName = (typeof SERVICE_NAMES)[number];

export const DEFAULT_ROOT_DIR = path.resolve(fileURLToPath(new URL('../../', import.meta.url)));

/** Services that survive a reset (not stopped, not restarted): the booth keeps visitor leads across demo resets. */
export const RESET_SURVIVORS: readonly ServiceName[] = ['booth'];

/** Readiness polling interval for health URLs (kept tight: it is on the reset's critical path). */
export const HEALTH_POLL_MS = 40;

export interface LaunchOptions {
  /** Repo root (default: two levels above this file). */
  rootDir?: string;
  host?: string;
  /**
   * Ports; `ledger` defaults to gateway + 1, `orchestrator` to gateway + 2 and `ops` to gateway + 3
   * (7073 / 7074 / 7075 with the default gateway port).
   */
  ports?: {
    broker?: number;
    paymentApi?: number;
    gateway?: number;
    ledger?: number;
    orchestrator?: number;
    /** M4 operations service; default gateway + 3 (7075). */
    ops?: number;
    /** AI explainer; default gateway + 4 (7076). */
    assistant?: number;
    /** Booth (leads + analytics); default gateway + 5 (7077). */
    booth?: number;
  };
  /**
   * Port of the launcher control API (GET /status, POST /reset). Undefined = no control server and
   * LAUNCHER_CONTROL_URL is empty (the gateway then answers reset with 503). 0 = any free port.
   */
  controlPort?: number;
  /** Event-log directory; relative paths resolve against rootDir. */
  dataDir?: string;
  /** Delete dataDir before starting. */
  reset?: boolean;
  stageDelayMs?: number;
  settlementDelayMs?: number;
  /** Ambient payments per second generated by the orchestrator (env AMBIENT_RATE, default 0). */
  ambientRate?: number;
  /** Start the orchestrator (default true). */
  orchestrator?: boolean;
  /** M4: start the operations service (default true). The gateway's /api/ops/* answers 502 without it. */
  ops?: boolean;
  /** Start the AI explainer (default true). */
  assistant?: boolean;
  /** Start the booth service (default true). */
  booth?: boolean;
  /**
   * ASSISTANT_LLM for the assistant: 'auto' = phrase answers with Claude when credentials work, 'off' =
   * grounded/cached answers only (fully offline). Default: env ASSISTANT_LLM, else 'off' (tests and verify
   * tools must never depend on the network; `npm start` passes 'auto').
   */
  assistantLlm?: 'auto' | 'off';
  /** Booth staff PIN (X-Booth-Staff). Default env BOOTH_STAFF_PIN, else the demo default 2468. */
  boothStaffPin?: string;
  /** Postgres URL for the ledger; empty/undefined = embedded PGlite under dataDir/ledger (env DATABASE_URL). */
  databaseUrl?: string;
  /** Simulation seed for markets and providers (env SIM_SEED). */
  simSeed?: string;
  /** Provider failure scale, 0 disables failures (env PROVIDER_FAILURE_SCALE). */
  providerFailureScale?: number;
  /** Extra environment for every child (wins over the computed values). */
  env?: Record<string, string>;
  /** Suppress child log lines (errors and timeouts are still reported). */
  quiet?: boolean;
  /** Run `npm run build:web` if apps/web/dist/index.html is missing (default true). Never on reset. */
  buildWeb?: boolean;
  /** Per-service readiness timeout (default 30s). */
  startupTimeoutMs?: number;
  /** Where log lines go (default: process.stdout). */
  log?: (line: string) => void;
  /** Called once if a service dies after startup (or a reset fails); everything has already been stopped. */
  onUnexpectedExit?: (error: Error) => void;
}

export interface StartupTiming {
  /** Wall time of the whole start phase. */
  totalMs: number;
  /** ms from the start of the phase until each service was ready. */
  ready: Record<string, number>;
}

export interface LaunchedSystem {
  /** `control` is present only when the control API runs (controlPort set). */
  urls: {
    gateway: string;
    paymentApi: string;
    broker: string;
    ledger: string;
    orchestrator: string;
    ops: string;
    /** Present when the assistant was started. */
    assistant?: string;
    /** Present when the booth was started. */
    booth?: string;
    control?: string;
  };
  /** Names of the processes this launch manages (broker omitted with BUS=kafka). */
  services: readonly ServiceName[];
  /** How long the initial start took and when each service became ready. */
  startup: StartupTiming;
  /**
   * Kill one service (whole process tree, no graceful shutdown: a crash, for chaos tests). The rest of
   * the system keeps running and the exit is not treated as a failure. No-op if it is not running.
   */
  kill(name: ServiceName): Promise<void>;
  /** Kill (if running) and start one service again; resolves once it is ready (health URL / ready line). */
  restart(name: ServiceName): Promise<void>;
  /**
   * The 10-second reset: stop every service, delete the data dir (same safety checks as --reset), start
   * everything again (no UI build). Resolves once every service, gateway included, is ready. Rejects with
   * ResetBusyError while another reset runs. If the restart fails, everything is stopped, the promise
   * rejects and onUnexpectedExit is called.
   */
  reset(): Promise<ResetResult>;
  /** What GET /status of the control API returns. */
  status(): LauncherStatus;
  /** True while the service's process is alive. */
  isRunning(name: ServiceName): boolean;
  stop(): Promise<void>;
}

