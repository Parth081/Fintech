function useColor(): boolean {
  return Boolean(process.stdout.isTTY) && !process.env.NO_COLOR;
}

const PREFIX_WIDTH = 'reconciliation'.length + 2;

export function prefixLine(name: string, line: string, color = useColor()): string {
  const tag = `[${name}]`.padEnd(PREFIX_WIDTH + 1);
  if (!color) return `${tag}${line}`;
  return `\x1b[${COLORS[name] ?? 37}m${tag}\x1b[0m${line}`;
}

/** Services already tag their own lines ("[fx] ready"); drop that tag so it is not printed twice. */
export function stripOwnTag(name: string, line: string): string {
  const tag = `[${name}] `;
  return line.startsWith(tag) ? line.slice(tag.length) : line;
}

interface ServiceSpec {
  name: ServiceName;
  script: string;
  args?: string[];
  /** Readiness: HTTP GET healthUrl returns 200 and/or a stdout line matches readyLine (both when both are set). */
  healthUrl?: string;
  readyLine?: RegExp;
}

interface Running {
  spec: ServiceSpec;
  child: ChildProcess;
  tail: string[];
  sawReadyLine: boolean;
  readyWaiters: (() => void)[];
  /** Killed on purpose via kill()/restart()/reset()/stop(): its exit is not a crash. */
  intentional: boolean;
}

const TAIL_LINES = 25;

class StartupError extends Error {}

function sleep(ms: number): Promise<void> {
  return new Promise((r) => setTimeout(r, ms));
}

async function httpOk(url: string): Promise<boolean> {
  try {
    const res = await fetch(url, { signal: AbortSignal.timeout(1500) });
    await res.arrayBuffer().catch(() => undefined);
    return res.status === 200;
  } catch {
    return false;
  }
}

export async function launch(options: LaunchOptions = {}): Promise<LaunchedSystem> {
  const rootDir = path.resolve(options.rootDir ?? DEFAULT_ROOT_DIR);
  const host = options.host ?? process.env.HOST ?? '127.0.0.1';
  // Probe/connect via loopback when binding to all interfaces.
  const probeHost = host === '0.0.0.0' || host === '::' ? '127.0.0.1' : host;
  const brokerPort = options.ports?.broker ?? 7070;
  const paymentApiPort = options.ports?.paymentApi ?? 7071;
  const gatewayPort = options.ports?.gateway ?? 7072;
  const ledgerPort = options.ports?.ledger ?? gatewayPort + 1;
  const orchestratorPort = options.ports?.orchestrator ?? gatewayPort + 2;
  const opsPort = options.ports?.ops ?? gatewayPort + 3;
  const withOrchestrator = options.orchestrator ?? true;
  const withOps = options.ops ?? true;
  const assistantPort = options.ports?.assistant ?? gatewayPort + 4;
  const boothPort = options.ports?.booth ?? gatewayPort + 5;
  const withAssistant = options.assistant ?? true;
  const withBooth = options.booth ?? true;
  const assistantLlm = options.assistantLlm ?? (process.env.ASSISTANT_LLM === 'auto' ? 'auto' : 'off');
  const boothStaffPin = options.boothStaffPin ?? (process.env.BOOTH_STAFF_PIN || '2468');
  const controlPort = options.controlPort;
  const dataDir = path.resolve(rootDir, options.dataDir ?? '.data');
  const timeoutMs = options.startupTimeoutMs ?? 30_000;
  const quiet = options.quiet ?? false;
  const write = options.log ?? ((l: string) => process.stdout.write(`${l}\n`));
  const say = (msg: string): void => write(prefixLine('launcher', msg));
  const bus = options.env?.BUS ?? process.env.BUS ?? 'local';
  const ambientRate = options.ambientRate ?? (process.env.AMBIENT_RATE ? Number(process.env.AMBIENT_RATE) : 0);

  // 1. Ports first: fail fast with a helpful message instead of a cryptic EADDRINUSE later.
  const wanted = [
    ...(bus === 'kafka' ? [] : [{ name: 'broker', port: brokerPort }]),
    { name: 'payment-api', port: paymentApiPort },
    { name: 'gateway', port: gatewayPort },
    { name: 'ledger', port: ledgerPort },
    ...(withOrchestrator ? [{ name: 'orchestrator', port: orchestratorPort }] : []),
    ...(withOps ? [{ name: 'ops', port: opsPort }] : []),
    ...(withAssistant ? [{ name: 'assistant', port: assistantPort }] : []),
    ...(withBooth ? [{ name: 'booth', port: boothPort }] : []),
    ...(controlPort ? [{ name: 'launcher control', port: controlPort }] : []),
  ];
  if (new Set(wanted.map((w) => w.port)).size !== wanted.length) {
    throw new StartupError(`Ports must be different: ${wanted.map((w) => `${w.name} ${w.port}`).join(', ')}`);
  }
  const busy = await findBusyPorts(wanted, probeHost);
  if (busy.length > 0) throw new StartupError(busyPortsMessage(busy, probeHost));

  // 2. Reset data if asked (also checked up front so a reset over HTTP can never hit a bad path).
  assertSafeToDelete(dataDir, rootDir);
  if (options.reset) {
    wipeDataDir(dataDir, rootDir);
    say(`reset: deleted ${dataDir} (kept ${PRESERVED_DATA_ENTRIES.join(', ')}: visitor leads survive resets; npm run booth:clear-leads)`);
  }

  // 3. Control server (before the services, so the gateway gets its URL).
  // The controller is wired to the real reset()/status() once they exist; until the first start is
  // complete a reset is refused with 409 (busy) and /status reports what has been started so far.
  let controller: { status: () => LauncherStatus; reset: () => Promise<ResetResult> } = {
    status: () => ({ services: [], startedAt: new Date().toISOString(), resetting: false, resets: 0, lastReset: null }),
    reset: () => Promise.reject(new ResetBusyError('the system is still starting')),
  };
  let control: ControlServerHandle | null = null;
  if (controlPort !== undefined) {
    control = await startControlServer({
      host: probeHost,
      port: controlPort,
      controller: { status: () => controller.status(), reset: () => controller.reset() },
      log: say,
    });
  }

  const urls = {
    broker: `ws://${probeHost}:${brokerPort}`,
    paymentApi: `http://${probeHost}:${paymentApiPort}`,
    gateway: `http://${probeHost}:${gatewayPort}`,
    ledger: `http://${probeHost}:${ledgerPort}`,
    orchestrator: `http://${probeHost}:${orchestratorPort}`,
    ops: `http://${probeHost}:${opsPort}`,
    ...(withAssistant ? { assistant: `http://${probeHost}:${assistantPort}` } : {}),
    ...(withBooth ? { booth: `http://${probeHost}:${boothPort}` } : {}),
    ...(control ? { control: control.url } : {}),
  };

  const webDist = path.join(rootDir, 'apps', 'web', 'dist');
  const childEnv: NodeJS.ProcessEnv = {
    ...process.env,
    CT_SUPERVISED: '1',
    HOST: host,
    BROKER_PORT: String(brokerPort),
    PAYMENT_API_PORT: String(paymentApiPort),
    GATEWAY_PORT: String(gatewayPort),
    LEDGER_PORT: String(ledgerPort),
    ORCHESTRATOR_PORT: String(orchestratorPort),
    OPS_PORT: String(opsPort),
    ASSISTANT_PORT: String(assistantPort),
    BOOTH_PORT: String(boothPort),
    ...(control ? { LAUNCHER_CONTROL_PORT: String(control.port) } : {}),
    BUS: bus,
    BROKER_URL: urls.broker,
    PAYMENT_API_URL: urls.paymentApi,
    GATEWAY_URL: urls.gateway,
    LEDGER_URL: urls.ledger,
    ORCHESTRATOR_URL: urls.orchestrator,
    OPS_URL: urls.ops,
    // Always set, even when not started: the gateway then answers /api/assistant|booth/* with 502.
    ASSISTANT_URL: urls.assistant ?? `http://${probeHost}:${assistantPort}`,
    BOOTH_URL: urls.booth ?? `http://${probeHost}:${boothPort}`,
    ASSISTANT_LLM: assistantLlm,
    BOOTH_STAFF_PIN: boothStaffPin,
    LAUNCHER_CONTROL_URL: urls.control ?? '',
    AMBIENT_RATE: String(ambientRate),
    DATA_DIR: dataDir,
    DATABASE_URL: options.databaseUrl ?? process.env.DATABASE_URL ?? '',
    SIM_SEED: options.simSeed ?? process.env.SIM_SEED ?? 'control-tower',
    PROVIDER_FAILURE_SCALE: String(options.providerFailureScale ?? process.env.PROVIDER_FAILURE_SCALE ?? 1),
    WEB_DIST: webDist,
    STAGE_DELAY_MS: String(options.stageDelayMs ?? process.env.STAGE_DELAY_MS ?? 400),
    SETTLEMENT_DELAY_MS: String(options.settlementDelayMs ?? process.env.SETTLEMENT_DELAY_MS ?? 900),
    ...options.env,
  };

  /** Every process of the current generation (a reset starts a new generation). */
  let running: Running[] = [];
  /** Every child still alive, of any generation: stop() kills all of them. */
  const alive = new Set<Running>();
  const specs = new Map<ServiceName, ServiceSpec>();
  const restarting = new Set<Promise<void>>();
  let stopping = false;
  let stopPromise: Promise<void> | undefined;
  let resetPromise: Promise<ResetResult> | null = null;
  let resets = 0;
  let lastReset: LauncherStatus['lastReset'] = null;
  let startedAt = new Date().toISOString();

  /** Kill every given process tree in parallel; their exits are intentional. */
  const killAll = async (rs: Iterable<Running>): Promise<void> => {
    const list = [...rs];
    for (const r of list) r.intentional = true;
    await Promise.all(list.map((r) => killTree(r.child)));
  };

  const stop = (): Promise<void> => {
    if (!stopPromise) {
      stopping = true;
      stopPromise = (async () => {
        // Stop in reverse dependency order (gateway + orchestrator, then api + stages + ledger, then
        // broker) so consumers do not log broker-disconnect noise. Each tier is killed in parallel.
        const tier = (r: Running): number =>
          r.spec.name === 'gateway' || r.spec.name === 'orchestrator' || r.spec.name === 'ops' || r.spec.name === 'assistant' ? 0 : r.spec.name === 'broker' ? 2 : 1;
        await Promise.allSettled(restarting);
        // The booth holds visitor leads: ask it to close its database cleanly first (closing stdin
        // triggers exitWithSupervisor), and only then kill whatever is left.
        await Promise.all([...alive].filter((r) => r.spec.name === 'booth').map((r) => gracefulStop(r, 4000)));
        for (const t of [0, 1, 2]) await killAll([...alive].filter((r) => tier(r) === t));
        // A reset that was starting services has seen `stopping` and spawns nothing more; kill whatever
        // it spawned meanwhile, then let it settle.
        await killAll(alive);
        if (resetPromise) await resetPromise.catch(() => undefined);
        await killAll(alive);
        await control?.close();
      })();
    }
    return stopPromise;
  };

  /** Close the child's stdin (the supervised service shuts down cleanly) and wait; kill the tree after graceMs. */
  const gracefulStop = async (r: Running, graceMs: number): Promise<void> => {
    r.intentional = true;
    try {
      r.child.stdin?.end();
    } catch {
      /* already closed */
    }
    await waitForExit(r.child, graceMs);
    await killTree(r.child);
  };

  const describeFailure = (r: Running, why: string): string => {
    const tail = r.tail.length ? r.tail.map((l) => `    ${l}`).join('\n') : '    (no output)';
    return `${why}\n  Last log lines from [${r.spec.name}]:\n${tail}`;
  };

  let started = false;
  let reportedCrash = false;
  /** First service that died while the system was (re)starting. */
  let startupCrash: Running | undefined;
  let crashWaiters: (() => void)[] = [];
  const onExit = (r: Running, code: number | null, signal: NodeJS.Signals | null): void => {
    alive.delete(r);
    if (stopping || r.intentional) return;
    if (!started) {
      startupCrash ??= r;
      for (const w of crashWaiters.splice(0)) w();
      return;
    }
    // Windows delivers Ctrl+C to children too; give our own SIGINT handler a moment to set `stopping`.
    setTimeout(() => {
      if (stopping || reportedCrash || r.intentional) return;
      reportedCrash = true;
      const err = new Error(
        describeFailure(r, `Service [${r.spec.name}] exited unexpectedly (code ${code}, signal ${signal}). Stopping everything.`),
      );
      write(prefixLine('launcher', err.message));
      void stop().then(() => {
        if (options.onUnexpectedExit) options.onUnexpectedExit(err);
      });
    }, 300);
  };

  const start = (spec: ServiceSpec): Running => {
    if (stopping) throw new StartupError('the launcher is stopping');
    specs.set(spec.name, spec);
    const r: Running = { spec, child: undefined as unknown as ChildProcess, tail: [], sawReadyLine: false, readyWaiters: [], intentional: false };
    r.child = spawnTs({
      rootDir,
      script: spec.script,
      args: spec.args,
      env: childEnv,
      onLine: (line) => {
        r.tail.push(line);
        if (r.tail.length > TAIL_LINES) r.tail.shift();
        if (!quiet) write(prefixLine(spec.name, stripOwnTag(spec.name, line)));
        if (spec.readyLine && !r.sawReadyLine && spec.readyLine.test(line)) {
          r.sawReadyLine = true;
          for (const w of r.readyWaiters.splice(0)) w();
        }
      },
    });
    r.child.on('error', (e) => r.tail.push(`spawn error: ${e.message}`));
    r.child.on('exit', (code, signal) => onExit(r, code, signal));
    running.push(r);
    alive.add(r);
    return r;
  };

  const waitReady = async (r: Running): Promise<void> => {
    const deadline = Date.now() + timeoutMs;
    const exited = (): boolean => stopping || !isRunning(r.child) || startupCrash !== undefined;
    let healthy = !r.spec.healthUrl;
    if (r.spec.healthUrl) {
      while (Date.now() < deadline) {
        if (exited()) break;
        if (await httpOk(r.spec.healthUrl)) {
          healthy = true;
          break;
        }
        await sleep(HEALTH_POLL_MS);
      }
    }
    if (healthy && !r.spec.readyLine) return;
    if (healthy && r.spec.readyLine) {
      if (r.sawReadyLine) return;
      await new Promise<void>((resolve) => {
        const timer = setTimeout(resolve, Math.max(0, deadline - Date.now()));
        const done = (): void => {
          clearTimeout(timer);
          resolve();
        };
        r.readyWaiters.push(done);
        crashWaiters.push(done);
        r.child.once('exit', done);
        if (startupCrash || !isRunning(r.child)) done();
      });
      if (r.sawReadyLine) return;
    }
    if (stopping) throw new StartupError('the launcher is stopping');
    const culprit = startupCrash ?? r;
    // Let trailing output arrive before quoting it.
    await waitForExit(culprit.child, 200);
    if (culprit !== r) {
      throw new StartupError(
        describeFailure(culprit, `Service [${culprit.spec.name}] exited during startup (code ${culprit.child.exitCode}).`),
      );
    }
    const why = !isRunning(r.child)
      ? `Service [${r.spec.name}] exited during startup (code ${r.child.exitCode}).`
      : `Service [${r.spec.name}] did not become ready within ${timeoutMs} ms ` +
        (!healthy ? `(GET ${r.spec.healthUrl} never returned 200).` : `(no stdout line matching ${r.spec.readyLine}).`);
    throw new StartupError(describeFailure(r, why));
  };

  const SPEC = {
    broker: { name: 'broker', script: 'services/broker/src/index.ts', healthUrl: `http://${probeHost}:${brokerPort}/health` },
    'payment-api': { name: 'payment-api', script: 'services/payment-api/src/index.ts', healthUrl: `${urls.paymentApi}/health` },
    ledger: { name: 'ledger', script: 'services/ledger/src/index.ts', healthUrl: `${urls.ledger}/health` },
    orchestrator: { name: 'orchestrator', script: 'services/orchestrator/src/index.ts', healthUrl: `${urls.orchestrator}/health` },
    gateway: { name: 'gateway', script: 'services/gateway/src/index.ts', healthUrl: `${urls.gateway}/health` },
    // Health answers as soon as it listens; "ready" is printed once the store is open and the log replayed.
    ops: { name: 'ops', script: 'services/ops/src/index.ts', healthUrl: `${urls.ops}/health`, readyLine: /\bready\b/i },
    assistant: { name: 'assistant', script: 'services/assistant/src/index.ts', healthUrl: `http://${probeHost}:${assistantPort}/health` },
    booth: { name: 'booth', script: 'services/booth/src/index.ts', healthUrl: `http://${probeHost}:${boothPort}/health` },
  } satisfies Partial<Record<ServiceName, ServiceSpec>>;
  const stageSpec = (s: Stage): ServiceSpec => ({ name: s, script: 'services/stages/src/index.ts', args: ['--stage', s], readyLine: /\bready\b/i });

  /**
   * Start every service and wait until all are ready. The critical path is kept short:
   *   t0      broker + ledger (the ledger opens PGlite first, the slowest step, and only then the bus)
   *   broker  payment-api, 6 stages, gateway (all connect to the bus; their clients retry anyway)
   *   api     orchestrator (it posts ambient payments to the payment API)
   *   broker  ops (projects the log into its store; the gateway proxies /api/ops/* to it)
   *   M5: booth at t0 (own PGlite, no bus) unless it is still running (a reset keeps it); assistant once
   *   the broker is up (it reads the event log).
   */
  const bootAll = async (): Promise<StartupTiming> => {
    const t0 = Date.now();
    const ready: Record<string, number> = {};
    const track = async (r: Running): Promise<void> => {
      await waitReady(r);
      ready[r.spec.name] = Date.now() - t0;
    };
    const waits: Promise<void>[] = [];
    // Waits that nobody awaits yet must not become unhandled rejections; Promise.all below reports them.
    const add = (p: Promise<void>): Promise<void> => {
      p.catch(() => undefined);
      waits.push(p);
      return p;
    };
    if (withBooth) {
      const kept = [...alive].find((r) => r.spec.name === 'booth' && isRunning(r.child));
      if (kept) {
        if (!running.includes(kept)) running.push(kept);
      } else {
        add(track(start(SPEC.booth)));
      }
    }
    if (bus !== 'kafka') {
      const broker = start(SPEC.broker);
      add(track(start(SPEC.ledger)));
      await track(broker);
    } else {
      add(track(start(SPEC.ledger)));
    }
    const api = start(SPEC['payment-api']);
    const apiReady = add(track(api));
    for (const s of STAGES) add(track(start(stageSpec(s))));
    if (withOps) add(track(start(SPEC.ops)));
    add(track(start(SPEC.gateway)));
    if (withAssistant) add(track(start(SPEC.assistant)));
    if (withOrchestrator) {
      add(
        apiReady.then(async () => {
          await track(start(SPEC.orchestrator));
        }),
      );
    }
    // Promise.all rejects with the first failure; give the remaining ones a moment to settle.
    await Promise.all(waits);
    return { totalMs: Date.now() - t0, ready };
  };

  const startup: StartupTiming = { totalMs: 0, ready: {} };
  try {
    // 4. UI build (only when missing; never on reset).
    if ((options.buildWeb ?? true) && !existsSync(path.join(webDist, 'index.html'))) {
      say('apps/web/dist is missing - building the UI (npm run build:web)...');
      const tail: string[] = [];
      const build = spawnShell('npm run build:web', rootDir, process.env, (line) => {
        tail.push(line);
        if (tail.length > TAIL_LINES) tail.shift();
        if (!quiet) write(prefixLine('build:web', line));
      });
      const code = await new Promise<number | null>((resolve) => {
        build.once('error', () => resolve(-1));
        build.once('exit', (c) => resolve(c));
      });
      if (code !== 0) {
        throw new StartupError(
          `UI build failed (npm run build:web exited with ${code}).\n${tail.map((l) => `    ${l}`).join('\n')}`,
        );
      }
    }

    // 5. Every service.
    Object.assign(startup, await bootAll());
    started = true;
    startedAt = new Date().toISOString();
  } catch (e) {
    await stop();
    throw e;
  }

  const current = (name: ServiceName): Running | undefined => {
    for (let i = running.length - 1; i >= 0; i--) if (running[i]!.spec.name === name) return running[i];
    return undefined;
  };

  const kill = async (name: ServiceName): Promise<void> => {
    if (stopping || resetPromise) return;
    const r = current(name);
    if (!r) throw new Error(`unknown service "${name}" (have: ${[...specs.keys()].join(', ')})`);
    if (!isRunning(r.child)) return;
    r.intentional = true;
    await killTree(r.child);
  };

  const restart = (name: ServiceName): Promise<void> => {
    const spec = specs.get(name);
    if (!spec) return Promise.reject(new Error(`unknown service "${name}" (have: ${[...specs.keys()].join(', ')})`));
    if (resetPromise) return Promise.reject(new Error(`cannot restart ${name} while a reset is running`));
    const p = (async () => {
      await kill(name);
      if (stopping) return;
      const old = current(name);
      if (old) running.splice(running.indexOf(old), 1);
      const r = start(spec);
      if (!quiet) say(`restarting ${name}`);
      await waitReady(r);
    })();
    restarting.add(p);
    void p.finally(() => restarting.delete(p)).catch(() => {});
    return p;
  };

  const reset = (): Promise<ResetResult> => {
    if (stopping) return Promise.reject(new Error('the launcher is stopping'));
    if (resetPromise || !started) return Promise.reject(new ResetBusyError());
    const p = (async (): Promise<ResetResult> => {
      const t0 = Date.now();
      say('reset: stopping every service...');
      await Promise.allSettled(restarting);
      // Everything at once: nothing needs a graceful goodbye, the data is deleted next. The booth
      // (visitor leads) keeps running and keeps its data.
      started = false;
      await killAll([...alive].filter((r) => !RESET_SURVIVORS.includes(r.spec.name) || !isRunning(r.child)));
      const stopMs = Date.now() - t0;
      if (stopping) throw new Error('the launcher is stopping');

      const w0 = Date.now();
      wipeDataDir(dataDir, rootDir);
      const wipeMs = Date.now() - w0;
      say(`reset: deleted ${dataDir} (kept ${PRESERVED_DATA_ENTRIES.join(', ')}); starting every service...`);

      running = running.filter((r) => RESET_SURVIVORS.includes(r.spec.name) && isRunning(r.child));
      startupCrash = undefined;
      crashWaiters = [];
      reportedCrash = false;
      const timing = await bootAll();
      started = true;
      startedAt = new Date().toISOString();
      resets += 1;
      const result: ResetResult = {
        ok: true,
        durationMs: Date.now() - t0,
        phases: { stopMs, wipeMs, startMs: timing.totalMs },
        ready: timing.ready,
        resets,
      };
      lastReset = { ...result, at: startedAt };
      say(`reset: done in ${result.durationMs} ms (stop ${stopMs} ms, wipe ${wipeMs} ms, start ${timing.totalMs} ms)`);
      return result;
    })();
    resetPromise = p;
    p.then(
      () => {
        resetPromise = null;
      },
      (err: unknown) => {
        resetPromise = null;
        if (stopping) return;
        const error = err instanceof Error ? err : new Error(String(err));
        lastReset = { ok: false, error: error.message, at: new Date().toISOString() };
        // Same as a crash after startup: stop everything, tell the owner (npm start exits non-zero).
        // The delay lets the HTTP caller get its 500 and lets a Ctrl+C in progress win.
        setTimeout(() => {
          if (stopping) return;
          write(prefixLine('launcher', `reset failed, stopping everything:\n${error.message}`));
          void stop().then(() => options.onUnexpectedExit?.(error));
        }, 300);
      },
    );
    return p;
  };

  const status = (): LauncherStatus => ({
    services: [...specs.keys()].map((name) => {
      const r = current(name);
      return { name, running: r !== undefined && isRunning(r.child) };
    }),
    startedAt,
    resetting: resetPromise !== null,
    resets,
    lastReset,
  });

  controller = { status, reset };

  return {
    urls,
    services: [...specs.keys()],
    startup,
    kill,
    restart,
    reset,
    status,
    isRunning: (name) => {
      const r = current(name);
      return r !== undefined && isRunning(r.child);
    },
    stop,
  };
}

export function banner(gatewayUrl: string, extra: string[] = []): string {
  const lines = [
    'Global Fintech Control Tower is running',
    '',
    `  Open ${gatewayUrl}`,
    `  Presenter console: ${gatewayUrl}/#/presenter`,
    `  Operations console: ${gatewayUrl}/#/console`,
    '  Then click "Send test payment", or run: npm run traffic -- --count 10',
    ...extra,
    '',
    '  Simulation · synthetic data · runs offline',
    '  Press Ctrl+C to stop all services.',
  ];
  const width = Math.max(...lines.map((l) => l.length)) + 2;
  const bar = '─'.repeat(width);
  return [`┌${bar}┐`, ...lines.map((l) => `│ ${l.padEnd(width - 1)}│`), `└${bar}┘`].join('\n');
}
